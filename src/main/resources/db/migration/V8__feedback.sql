-- Feedback sent through the site: corrections, complaints, suggestions, ideas. Guests can send it too,
-- so user_id and email are optional. about_type / about_ref say what it is about (e.g. ARTIST / "Ajja").
create table feedback (
    id         bigint generated by default as identity,
    kind       varchar(20)                 not null,
    about_type varchar(20),
    about_ref  varchar(200),
    page_url   varchar(500),
    message    varchar(2000)               not null,
    email      varchar(255),
    user_id    bigint references app_user (id),
    status     varchar(20)                 not null default 'NEW',
    created_at timestamp(6) with time zone not null,
    primary key (id)
);

-- The admin list shows the newest first, usually filtered by status
create index ix_feedback_status_created on feedback (status, created_at desc);
