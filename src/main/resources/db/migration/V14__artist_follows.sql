-- Artists a user follows: their ships glow gold on the map, and the user is emailed when they get a new gig.
-- The slug is the artist's from the line-ups (artists.slug); the name is kept for lists.
create table artist_follows (
    id          bigint generated by default as identity,
    user_id     bigint                      not null references app_user (id),
    artist_slug varchar(100)                not null,
    artist_name varchar(100)                not null,
    created_at  timestamp(6) with time zone not null,
    primary key (id),
    constraint uk_artist_follows_user_artist unique (user_id, artist_slug)
);

-- Gigs a follower already knows about: emailed, or already listed when they started following.
-- One row per user and event, so an event with two followed artists is mailed once.
create table follow_notices (
    id       bigint generated by default as identity,
    user_id  bigint                      not null references app_user (id),
    event_id bigint                      not null,
    noted_at timestamp(6) with time zone not null,
    primary key (id),
    constraint uk_follow_notices_user_event unique (user_id, event_id)
);
