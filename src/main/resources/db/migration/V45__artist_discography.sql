-- An artist's country, first year and albums, edited by the artist (or an admin) instead of the bundled
-- map/artists.json, which only fills these tables the first time (ArtistDiscography).
create table artist_discography
(
    artist_slug varchar(100) not null primary key,
    country     varchar(100),
    since       integer,
    updated_by  varchar(255),
    updated_at  timestamp(6) with time zone
);

create table artist_albums
(
    id          bigint generated by default as identity primary key,
    artist_slug varchar(100) not null,
    position    integer      not null,
    title       varchar(200) not null,
    year        integer
);

create index ix_artist_albums_slug on artist_albums (artist_slug);

-- Bundled data copied into the database once (name: what was copied), so a restart never copies it again
create table data_seeds
(
    name    varchar(60) not null primary key,
    done_at timestamp(6) with time zone not null
);
