-- "Claim this page": an account asks to own the page of an artist, organizer, label or festival, with a link that
-- shows it is them. It is approved by itself when the account's confirmed email is on the page's official website's
-- domain, otherwise by an admin. target: the artist's or organizer's slug, the label's name or the festival's id.
create table page_claims (
    id            bigint generated by default as identity,
    kind          varchar(20)                 not null,
    target        varchar(200)                not null,
    user_id       bigint                      not null references app_user (id),
    proof_url     varchar(500),
    message       varchar(1000),
    status        varchar(20)                 not null,
    created_at    timestamp(6) with time zone not null,
    decided_by    varchar(255),
    decided_at    timestamp(6) with time zone,
    reject_reason varchar(500),
    primary key (id)
);

create index ix_page_claims_status on page_claims (status);
create index ix_page_claims_user on page_claims (user_id);
