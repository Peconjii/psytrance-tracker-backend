-- Labels a user follows (by the label's name on the map): the gigs of the label's artists count as followed
-- gigs, on the map and in the new-gig emails. The roster comes from map/labels.json.
create table label_follows (
    id         bigint generated by default as identity,
    user_id    bigint                      not null references app_user (id),
    label_name varchar(200)                not null,
    created_at timestamp(6) with time zone not null,
    primary key (id),
    constraint uk_label_follows_user_label unique (user_id, label_name)
);
