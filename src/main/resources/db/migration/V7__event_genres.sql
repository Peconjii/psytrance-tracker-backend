-- Which Map of Psy genres an event plays, worked out when its line-up is read (see EventGenres).
-- share: the genre's part of the event, all shares of an event add up to 1.
-- source: the best evidence for the genre: ARTIST (artist placed in it on the map),
-- STAGE (named in a stage header of the line-up) or KEYWORD (genre the organizer picked on Goabase).
create table event_genres (
    id       bigint generated by default as identity,
    event_id bigint      not null,
    genre_id varchar(30) not null,
    share    real        not null,
    source   varchar(10) not null,
    primary key (id),
    constraint uk_event_genres_event_genre unique (event_id, genre_id)
);
