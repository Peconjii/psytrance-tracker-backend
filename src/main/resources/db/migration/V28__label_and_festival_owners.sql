-- Labels and festivals of the map get owners, like artists and organizers: an admin links the account of someone from
-- the label or the festival, who then writes its page. A label's crew changes go to an admin first.

create table label_profiles (
    label_name    varchar(200)                not null,
    description   varchar(2000),
    logo_url      varchar(500),
    website_url   varchar(300),
    bandcamp_url  varchar(300),
    instagram_url varchar(300),
    updated_at    timestamp(6) with time zone not null,
    primary key (label_name)
);

create table label_owners (
    label_name varchar(200)                not null,
    user_id    bigint                      not null references app_user (id),
    created_at timestamp(6) with time zone not null,
    primary key (label_name)
);

create index ix_label_owners_user on label_owners (user_id);

-- Approved changes to a label's crew on top of map/labels.json: added = on the label now, not added = taken off it
create table label_crew (
    label_name  varchar(200)                not null,
    artist_name varchar(100)                not null,
    added       boolean                     not null,
    decided_by  varchar(255)                not null,
    decided_at  timestamp(6) with time zone not null,
    primary key (label_name, artist_name)
);

-- An owner asks to put an artist on the label (ADD) or take one off (REMOVE); an admin decides
create table label_requests (
    id          bigint generated by default as identity,
    label_name  varchar(200)                not null,
    kind        varchar(20)                 not null,
    artist_name varchar(100)                not null,
    user_id     bigint                      not null references app_user (id),
    status      varchar(20)                 not null,
    created_at  timestamp(6) with time zone not null,
    decided_by  varchar(255),
    decided_at  timestamp(6) with time zone,
    primary key (id)
);

create index ix_label_requests_status on label_requests (status);

-- A festival's own words and links, and the organizer who runs it (organizers.slug)
create table festival_profiles (
    festival_id    varchar(60)                 not null,
    description    varchar(2000),
    website_url    varchar(300),
    ticket_url     varchar(300),
    instagram_url  varchar(300),
    organizer_slug varchar(100),
    updated_at     timestamp(6) with time zone not null,
    primary key (festival_id)
);

create table festival_owners (
    festival_id varchar(60)                 not null,
    user_id     bigint                      not null references app_user (id),
    created_at  timestamp(6) with time zone not null,
    primary key (festival_id)
);

create index ix_festival_owners_user on festival_owners (user_id);
