-- Which artists orbit which genre star on the map. Filled from map/genres.json on first start, then edited by
-- admins in the admin panel. An artist can be placed in several genres; rows keep their insertion order.
create table map_artist_genres (
    id          bigint generated by default as identity,
    artist_name varchar(100) not null,
    genre_id    varchar(30)  not null,
    primary key (id),
    constraint uk_map_artist_genres_artist_genre unique (artist_name, genre_id)
);

-- What admins changed, so a change can be looked up and undone. Values are short readable texts
-- such as "forest, night".
create table admin_changes (
    id           bigint generated by default as identity,
    username     varchar(255)                not null,
    kind         varchar(40)                 not null,
    target       varchar(200)                not null,
    before_value varchar(2000),
    after_value  varchar(2000),
    created_at   timestamp(6) with time zone not null,
    primary key (id)
);

create index ix_admin_changes_created on admin_changes (created_at desc);
