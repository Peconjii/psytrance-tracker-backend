-- A new account confirms its email by opening a link that was mailed to it. Until then it can do everything
-- except add events. Accounts made before this count as verified.
alter table app_user add column email_verified boolean not null default false;
update app_user set email_verified = true;

-- The emailed links: like password_reset_tokens, only a SHA-256 hash of the token is stored. One per user (the newest).
create table email_verification_tokens (
    id         bigint generated by default as identity,
    token_hash varchar(64)                 not null unique,
    user_id    bigint                      not null references app_user (id),
    created_at timestamp(6) with time zone not null,
    expires_at timestamp(6) with time zone not null,
    primary key (id)
);
