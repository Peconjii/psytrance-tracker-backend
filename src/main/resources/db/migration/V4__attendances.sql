-- "I'm going" marks: one row per user and event. Name and start date are copied from Goabase,
-- so the profile can list them without asking Goabase about every event.
create table attendances (
    id         bigint generated by default as identity,
    user_id    bigint                      not null references app_user (id),
    event_id   bigint                      not null,
    event_name varchar(255),
    starts_on  date,
    created_at timestamp(6) with time zone not null,
    primary key (id),
    constraint uk_attendances_user_event unique (user_id, event_id)
);

-- Counting who goes to an event is the most common query
create index ix_attendances_event on attendances (event_id);
