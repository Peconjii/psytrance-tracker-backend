-- Users can turn reminder emails off on their profile; everyone starts with them on
alter table app_user add column event_reminders boolean not null default true;

-- Which reminder emails were already sent, so nobody gets the same reminder twice
create table event_reminders (
    id       bigint generated by default as identity,
    user_id  bigint                      not null references app_user (id),
    event_id bigint                      not null,
    sent_at  timestamp(6) with time zone not null,
    primary key (id),
    constraint uk_event_reminders_user_event unique (user_id, event_id)
);
