-- Artists found in event line-ups. The slug is the name in lower case without accents or symbols
-- ("Ace Ventura" -> "ace-ventura"), so the same artist written differently is stored once.
create table artists (
    id   bigint generated by default as identity,
    slug varchar(100) not null,
    name varchar(100) not null,
    primary key (id),
    constraint uk_artists_slug unique (slug)
);

-- Who plays at which event
create table artist_events (
    id        bigint generated by default as identity,
    artist_id bigint not null references artists (id),
    event_id  bigint not null,
    primary key (id),
    constraint uk_artist_events_artist_event unique (artist_id, event_id)
);

create index ix_artist_events_event on artist_events (event_id);

-- When each event's line-up was last read from Goabase
create table lineup_scans (
    event_id   bigint                      not null,
    scanned_at timestamp(6) with time zone not null,
    primary key (event_id)
);
