-- Events added on our site, next to the ones from Goabase. A verified account sends one; an admin approves it (or the
-- organizer's page owner and admins add theirs right away). Once approved it is listed like a Goabase party with the
-- id 1 000 000 000 + id, so it gets the same line-up index, genres, ship and event page.
create table our_events (
    id                 bigint generated by default as identity,
    submitted_by       bigint                      not null references app_user (id),
    status             varchar(20)                 not null,
    name               varchar(200)                not null,
    event_type         varchar(40)                 not null,
    starts_at          timestamp(6)                not null,
    ends_at            timestamp(6),
    time_zone          varchar(60)                 not null,
    country            varchar(100)                not null,
    town               varchar(100)                not null,
    lat                double precision            not null,
    lon                double precision            not null,
    line_up            text,
    location_text      text,
    entry_fee          varchar(500),
    info               text,
    organizer_name     varchar(200),
    organizer_url      varchar(500),
    ticket_url         varchar(500),
    image_url          varchar(500),
    genres             varchar(200)                not null default '',
    created_at         timestamp(6) with time zone not null,
    decided_at         timestamp(6) with time zone,
    decided_by         varchar(255),
    reject_reason      varchar(500),
    primary key (id)
);

create index idx_our_events_status on our_events (status);
create index idx_our_events_submitted_by on our_events (submitted_by);
