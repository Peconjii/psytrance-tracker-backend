-- "Not on the map yet?": an account asks for a page of an artist, organizer, label or festival the site doesn't know.
-- An admin decides; approving an artist or organizer makes the page and its owner, a label or festival is noted for
-- the next update of the map's data (created_slug stays null then).
create table page_requests
(
    id            bigint generated by default as identity,
    kind          varchar(20)                 not null,
    name          varchar(200)                not null,
    country       varchar(100),
    website_url   varchar(500),
    proof_url     varchar(500),
    genres        varchar(300),
    message       varchar(1000),
    user_id       bigint                      not null references app_user (id),
    status        varchar(20)                 not null,
    created_at    timestamp(6) with time zone not null,
    decided_by    varchar(255),
    decided_at    timestamp(6) with time zone,
    reject_reason varchar(500),
    created_slug  varchar(100),
    primary key (id)
);

create index ix_page_requests_status on page_requests (status);
create index ix_page_requests_user on page_requests (user_id);
