-- Pictures people upload (a photo, a logo, a flyer), kept in the database: Render's disk is wiped on every deploy.
-- The browser makes them small first (~200 KB). A picture nothing points to any more is deleted after a day
-- (Images.deleteUnused), so replaced and abandoned ones don't pile up.
create table images
(
    id           bigint generated by default as identity,
    user_id      bigint references app_user (id) on delete set null,
    content_type varchar(20)                 not null,
    size         integer                     not null,
    data         bytea                       not null,
    created_at   timestamp(6) with time zone not null,
    primary key (id)
);

