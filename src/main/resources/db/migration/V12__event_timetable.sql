-- Set times of an event: read from its line-up (AUTO) or set by an admin (MANUAL, the artist index leaves them alone).
-- Times are on the clock at the venue, like the event times on the event page; utc_offset_minutes says how that clock
-- relates to UTC (from Goabase), for showing which set is playing right now.
create table event_timetable (
    id          bigint generated by default as identity,
    event_id    bigint                      not null,
    position    integer                     not null,
    stage       varchar(100),
    artist_name varchar(100)                not null,
    starts_at   timestamp(6) not null,
    ends_at     timestamp(6),
    utc_offset_minutes integer,
    source      varchar(10)                 not null,
    primary key (id)
);

create index ix_event_timetable_event on event_timetable (event_id, position);
