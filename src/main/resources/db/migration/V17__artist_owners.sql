-- The account that owns an artist's profile: an admin links it after the artist got in touch. The owner edits
-- the profile, tracks and festivals directly; genres and the name on the page go to an admin as requests.
create table artist_owners (
    artist_slug varchar(100)                not null,
    user_id     bigint                      not null references app_user (id),
    created_at  timestamp(6) with time zone not null,
    primary key (artist_slug)
);

create index ix_artist_owners_user on artist_owners (user_id);

-- Tracks the artist picks for their profile, in their order
create table artist_tracks (
    id          bigint generated by default as identity,
    artist_slug varchar(100) not null,
    position    integer      not null,
    title       varchar(200) not null,
    url         varchar(300) not null,
    primary key (id)
);

create index ix_artist_tracks_slug on artist_tracks (artist_slug);

-- Festivals the artist says they played, in their order
create table artist_festivals (
    id          bigint generated by default as identity,
    artist_slug varchar(100) not null,
    position    integer      not null,
    name        varchar(200) not null,
    year        integer,
    url         varchar(300),
    primary key (id)
);

create index ix_artist_festivals_slug on artist_festivals (artist_slug);

-- The name on the artist's page when it differs from the one in the line-ups (approved by an admin)
alter table artist_profiles add column display_name varchar(100);

-- Changes an owner asks for and an admin decides: GENRES (map genre ids, comma-separated) or NAME
create table artist_requests (
    id          bigint generated by default as identity,
    artist_slug varchar(100)                not null,
    kind        varchar(20)                 not null,
    value       varchar(500)                not null,
    user_id     bigint                      not null references app_user (id),
    status      varchar(20)                 not null,
    created_at  timestamp(6) with time zone not null,
    decided_by  varchar(255),
    decided_at  timestamp(6) with time zone,
    primary key (id)
);

create index ix_artist_requests_status on artist_requests (status, created_at);
